<?php

namespace Tests\Support;

/**
 * A Google-shaped ID token, minted locally so verification can be tested.
 *
 * The point of this class is that the tests exercise the real check: an RSA
 * signature over the exact bytes `App\Auth\Services\GoogleIdTokenVerifier`
 * expects, a key set in the shape Google publishes, and the freedom to break
 * one claim at a time. A test that replaced the verifier with a double would
 * prove the controller calls something; this proves the controller calls
 * something that works.
 *
 * The key pair is generated per process and thrown away. Nothing here is a
 * credential: no private key is committed, and the "Google" being imitated is
 * this file, reached only because the test points the JWKS URL at a fake HTTP
 * layer.
 */
trait FakeGoogleIdToken
{
    /** @var array{private-key: \OpenSSLAsymmetricKey, details: array}|null */
    protected static ?array $googleTestKey = null;

    /** @var string|null Path to the openssl configuration this trait writes. */
    protected static ?string $googleTestOpenSslConfig = null;

    protected const GOOGLE_TEST_JWKS_URL = 'https://certificates.example.test/oauth2/v3/certs';

    protected const GOOGLE_TEST_KID = 'test-signing-key-1';

    /**
     * The openssl configuration file key generation needs on this build.
     *
     * openssl's key generation needs somewhere to write its entropy state, and
     * a Windows PHP build ships without one configured. Setting both the config
     * and `RANDFILE` is the documented remedy and has no effect on a build that
     * already has them; without it `openssl_pkey_new()` returns false and every
     * test in this file would fail for a reason that has nothing to do with the
     * code under test. It is a method rather than two lines because the second
     * key below is generated by the same call.
     */
    protected function googleKeyConfig(): string
    {
        if (self::$googleTestOpenSslConfig !== null) {
            return self::$googleTestOpenSslConfig;
        }

        $randFile = sys_get_temp_dir() . DIRECTORY_SEPARATOR . 'hassal-test-rnd';
        $configFile = sys_get_temp_dir() . DIRECTORY_SEPARATOR . 'hassal-test-openssl.cnf';

        if (! is_file($configFile)) {
            file_put_contents(
                $configFile,
                "[ req ]\ndefault_bits = 2048\ndistinguished_name = dn\n[ dn ]\n[ req_dn ]\nCommonName = hassal-test\n"
            );
        }

        putenv('OPENSSL_CONF=' . $configFile);
        putenv('RANDFILE=' . $randFile);

        return self::$googleTestOpenSslConfig = $configFile;
    }

    /**
     * @return array{private-key: \OpenSSLAsymmetricKey, details: array}
     */
    protected function googleTestKey(): array
    {
        if (self::$googleTestKey !== null) {
            return self::$googleTestKey;
        }

        $configFile = $this->googleKeyConfig();

        $key = openssl_pkey_new([
            'config' => $configFile,
            'private_key_bits' => 2048,
            'private_key_type' => OPENSSL_KEYTYPE_RSA,
        ]);

        if ($key === false) {
            self::fail('This PHP build cannot generate an RSA key, so Google token verification cannot be tested here: '
                . (openssl_error_string() ?: 'no detail from openssl'));
        }

        return self::$googleTestKey = [
            'private-key' => $key,
            'details' => openssl_pkey_get_details($key),
        ];
    }

    /**
     * The document `GET {jwks_url}` answers with, in Google's shape.
     *
     * @return array{keys: list<array<string, string>>}
     */
    protected function googleTestJwks(?string $kid = null): array
    {
        $details = $this->googleTestKey()['details'];

        return [
            'keys' => [[
                'alg' => 'RS256',
                'use' => 'sig',
                'kty' => 'RSA',
                'kid' => $kid ?? self::GOOGLE_TEST_KID,
                'n' => $this->base64Url($details['rsa']['n']),
                'e' => $this->base64Url($details['rsa']['e']),
            ]],
        ];
    }

    /**
     * A signed ID token carrying these claims.
     *
     * Defaults are what a real Google token for a Gmail user carries. Every
     * field is overridable, and `null` removes a claim — which is how a test
     * says "a token with no expiry" rather than "a token with a fake expiry".
     *
     * @param  array<string, mixed>  $claims
     */
    protected function googleTestIdToken(array $claims = []): string
    {
        $now = now()->getTimestamp();

        $payload = [
            'iss' => 'https://accounts.google.com',
            'azp' => $this->googleClientId(),
            'aud' => $this->googleClientId(),
            'sub' => '108473910293847293841',
            'hd' => null,
            'email' => 'trader@example.test',
            'email_verified' => true,
            'name' => 'تاجر تجريبي',
            'picture' => 'https://avatars.example.test/1.png',
            'locale' => 'ar',
            'iat' => $now,
            'exp' => $now + 3600,
            'nonce' => 'test-nonce-value-0123456789',
        ];

        foreach ($claims as $claim => $value) {
            if ($value === null) {
                unset($payload[$claim]);

                continue;
            }

            $payload[$claim] = $value;
        }

        $signingInput = $this->base64Url(json_encode([
            'alg' => 'RS256',
            'kid' => self::GOOGLE_TEST_KID,
            'typ' => 'JWT',
        ], JSON_UNESCAPED_SLASHES))
            . '.'
            . $this->base64Url(json_encode($payload, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE));

        $signature = '';

        openssl_sign($signingInput, $signature, $this->googleTestKey()['private-key'], OPENSSL_ALGO_SHA256);

        return $signingInput . '.' . $this->base64Url($signature);
    }

    /**
     * A token whose bytes are signed by a key Google never published.
     */
    protected function googleTestIdTokenSignedByOtherKey(array $claims = []): string
    {
        // A different key pair, deliberately: the published one stays in the
        // fake JWKS so the only thing untrue about this token is who signed it.
        $this->googleTestKey();

        $foreign = openssl_pkey_new([
            'config' => $this->googleKeyConfig(),
            'private_key_bits' => 2048,
            'private_key_type' => OPENSSL_KEYTYPE_RSA,
        ]);

        if ($foreign === false) {
            self::fail('This PHP build cannot generate a second RSA key: '
                . (openssl_error_string() ?: 'no detail from openssl'));
        }

        $now = now()->getTimestamp();

        $payload = array_merge([
            'iss' => 'https://accounts.google.com',
            'aud' => $this->googleClientId(),
            'sub' => '99887766554433221100',
            'email' => 'attacker@example.test',
            'email_verified' => true,
            'iat' => $now,
            'exp' => $now + 3600,
            'nonce' => 'test-nonce-value-0123456789',
        ], $claims);

        $signingInput = $this->base64Url(json_encode([
            'alg' => 'RS256',
            'kid' => self::GOOGLE_TEST_KID,
            'typ' => 'JWT',
        ], JSON_UNESCAPED_SLASHES)) . '.' . $this->base64Url(json_encode($payload, JSON_UNESCAPED_SLASHES));

        $signature = '';
        openssl_sign($signingInput, $signature, $foreign, OPENSSL_ALGO_SHA256);

        return $signingInput . '.' . $this->base64Url($signature);
    }

    protected function googleTestNonce(): string
    {
        return 'test-nonce-value-0123456789';
    }

    protected function googleClientId(): string
    {
        return 'hassal-test-client-id.apps.googleusercontent.com';
    }

    private function base64Url(string $value): string
    {
        return rtrim(strtr(base64_encode($value), '+/', '-_'), '=');
    }
}
